#!/usr/bin/env python3
"""Scrive una piccola ROM SNES di prova (32 KB, LoROM): cambia colore di sfondo di continuo. Scritta da FMLAB, libera."""
import sys
rom = bytearray(b"\xff" * 0x8000)
codice = bytes([0x78, 0x18, 0xFB, 0xA9, 0x0F, 0x8D, 0x00, 0x21, 0x9C, 0x21, 0x21, 0xE8, 0x8A, 0x8D, 0x22, 0x21, 0x8D, 0x22, 0x21, 0x80, 0xF3])
rom[0:len(codice)] = codice
rom[0x7FC0:0x7FC0 + 21] = b"FMLAB BANCO DI PROVA ".ljust(21, b" ")[:21]
rom[0x7FD5] = 0x20; rom[0x7FD6] = 0; rom[0x7FD7] = 5; rom[0x7FD8] = 0; rom[0x7FD9] = 1; rom[0x7FDA] = 0; rom[0x7FDB] = 0
for v in (0x7FFC, 0x7FEA, 0x7FFA, 0x7FEC, 0x7FEE, 0x7FFE, 0x7FE4, 0x7FE6, 0x7FE8):
    rom[v] = 0x00; rom[v + 1] = 0x80
rom[0x7FDC:0x7FE0] = b"\xff\xff\x00\x00"
s = sum(rom) & 0xFFFF
rom[0x7FDE] = s & 0xFF; rom[0x7FDF] = s >> 8; c = s ^ 0xFFFF; rom[0x7FDC] = c & 0xFF; rom[0x7FDD] = c >> 8
open(sys.argv[1], "wb").write(rom)
